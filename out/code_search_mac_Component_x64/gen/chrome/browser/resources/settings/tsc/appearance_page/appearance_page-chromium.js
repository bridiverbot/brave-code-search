    onBookmarksBarVisibilitySettingsControlChange_(event) {
        const dropdown = event.target;
        const value = Number.parseInt(dropdown.getSelectedValue(), 10);
        // These values map to the BookmarkBarVisibilityState enum in
        // components/bookmarks/common/bookmark_bar_visibility_state.h.
        switch (value) {
            // Equivalent to `BookmarkBarVisibilityState::kAlwaysShow`.
            case 0:
                this.metricsBrowserProxy_.recordAction('Settings_BookmarkBar_AlwaysShow');
                break;
            // Equivalent to `BookmarkBarVisibilityState::kOnlyShowOnNtp`.
            case 1:
                this.metricsBrowserProxy_.recordAction('Settings_BookmarkBar_OnlyShowOnNtp');
                break;
            // Equivalent to `BookmarkBarVisibilityState::kAlwaysHide`.
            case 2:
                this.metricsBrowserProxy_.recordAction('Settings_BookmarkBar_AlwaysHide');
                break;
            default:
                assertNotReached();
        }
    }
