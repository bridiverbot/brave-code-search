    onManagedDialogClose_() {
        this.showManagedThemeDialog_ = false;
    }
    getOverrideValue_(id) {
        const overrides = this.sidePanelAlignmentOverridesPref_?.value;
        const defaultIsRight = this.sidePanelIsRightAlignedPref_?.value;
        if (defaultIsRight === undefined) {
            return '';
        }
        const isRight = (overrides && overrides[id] !== undefined) ? overrides[id] :
            defaultIsRight;
        return isRight.toString();
    }
    onOverrideAlignmentSettingsControlChange_(event) {
        const dropdown = event.target;
        const entryId = dropdown.dataset['entryId'];
        const newValue = dropdown.getSelectedValue() === 'true';
        PrefService.getInstance().setPrefDictEntry('side_panel.alignment_overrides', entryId, newValue);
    }
    // SettingsViewMixin
    getFocusConfig() {
        const map = new Map();
        if (routes.FONTS) {
            map.set(routes.FONTS.path, '#customize-fonts-subpage-trigger');
        }
        return map;
    }
    // SettingsViewMixin implementation.
    getAssociatedControlFor(childViewId) {
        assert(childViewId === 'fonts');
        const control = this.shadowRoot.querySelector('#customize-fonts-subpage-trigger');
        assert(control, `Failed to find associated control for child '${childViewId}'`);
        return control;
    }
